const PORT = process.env.PROBE_PORT || "9336";
const list = await (await fetch("http://127.0.0.1:" + PORT + "/json/list")).json();
console.log("targets:");
for (const t of list) console.log("  ", t.type, t.url.slice(0, 110));
const page = list.find((t) => t.type === "page" && /reader\.local/.test(t.url));
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0;
const pending = new Map();
const send = (m, p = {}) => new Promise((res, rej) => { const i = ++id; pending.set(i, { res, rej }); ws.send(JSON.stringify({ id: i, method: m, params: p })); });
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { const q = pending.get(m.id); pending.delete(m.id); m.error ? q.rej(new Error(JSON.stringify(m.error))) : q.res(m.result); } };
await new Promise((r) => (ws.onopen = r));
await send("Runtime.enable");
const ev = async (x) => { const r = await send("Runtime.evaluate", { expression: x, returnByValue: true }); return r.result ? r.result.value : undefined; };
console.log("readerHidden=", await ev("document.getElementById('reader').hidden"));
console.log("blocks=", await ev("document.querySelectorAll('#content .chapter-block').length"));
console.log("blockIdx=", await ev("Array.from(document.querySelectorAll('#content .chapter-block')).map(function(e){return e.dataset.index;}).join(',')"));
console.log("firstTitle=", await ev("(document.querySelector('#content .chapter-block .ch-title')||{}).textContent"));
console.log("firstParas=", await ev("(document.querySelector('#content .chapter-block')||{innerText:''}).innerText.slice(0,200)"));
console.log("status=", await ev("(document.getElementById('status')||{}).textContent"));
console.log("toast=", await ev("(document.getElementById('toast')||{}).textContent"));
ws.close();
