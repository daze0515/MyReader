const PORT = process.env.SHOT_PORT || "9336";
const fs = await import("node:fs");
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const list = await (await fetch("http://127.0.0.1:" + PORT + "/json/list")).json();
const page = list.find((t) => t.type === "page" && /reader[.]local/.test(t.url));
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
const send = (m, p = {}) => new Promise((res, rej) => { const i = ++id; pending.set(i, { res, rej }); ws.send(JSON.stringify({ id: i, method: m, params: p })); });
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { const q = pending.get(m.id); pending.delete(m.id); m.error ? q.rej(new Error(JSON.stringify(m.error))) : q.res(m.result); } };
await new Promise((r) => (ws.onopen = r));
await send("Page.enable");
await send("Runtime.enable");
const ev = async (x) => (await send("Runtime.evaluate", { expression: x, returnByValue: true, awaitPromise: true })).result.value;
await ev("(function(){document.getElementById(\"settings-panel\").hidden=true;document.getElementById(\"toc-drawer\").hidden=true;return 1;})()");
await ev("(function(){var v=document.getElementById(\"viewport\");v.scrollTop=0;return 1;})()");
await sleep(600);
const r = await send("Page.captureScreenshot", { format: "png" });
fs.writeFileSync(process.env.SHOT_OUT || "C:/Windows/Temp/reader69.png", Buffer.from(r.data, "base64"));
console.log("saved", process.env.SHOT_OUT || "C:/Windows/Temp/reader69.png");
ws.close();
